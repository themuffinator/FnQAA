"""Generate a recompiled module's glue: kernel import stubs, the module
descriptor the guest runtime reads, and the decoded image it maps.

The glue is build output (it embeds the user's decoded image); it is
written next to XenonRecomp's output, never into the repository.
"""
import os


def c_string(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def write_glue(out_dir, name, report, image_bytes, recompiler_id):
    """report: the analysis JSON dict (tools/recomp/analyse.py)."""
    os.makedirs(out_dir, exist_ok=True)
    img_path = os.path.join(out_dir, "image.bin")
    if not os.path.exists(img_path) or open(img_path, "rb").read() != image_bytes:
        with open(img_path, "wb") as f:
            f.write(image_bytes)

    imports = report["imports"]
    exports = report["exports"]
    nexp = max([int(k) for k in exports] or [0])
    lines = [
        "// Generated by tools/recomp/build.py for %s. Build output: never commit." % report["module"],
        '#include "ppc_recomp_shared.h"',
        '#include "qaa_module_abi.h"',
        "",
        "#ifdef _WIN32",
        '#define QAA_MODULE_EXPORT extern "C" __declspec(dllexport)',
        "#else",
        '#define QAA_MODULE_EXPORT extern "C" __attribute__((visibility("default")))',
        "#endif",
        "",
        "qaa::GuestFunc *const *const *qaa_module_func_pages;",
        "void (*qaa_module_indirect_miss)(PPCContext &ctx, uint8_t *base, uint32_t target);",
        "void (*qaa_module_trap)(PPCContext &ctx, uint8_t *base, uint32_t address);",
        "static void (*qaa_kernel_call)(uint32_t library, uint32_t ordinal, PPCContext &ctx, uint8_t *base);",
        "",
        "// Import thunks: the recompiled code calls these for each kernel import.",
    ]
    libs = {"xboxkrnl.exe": 0, "xam.xex": 1}
    for imp in imports:
        if imp["thunk"]:
            lines.append("PPC_FUNC(__imp__%s) { qaa_kernel_call(%d, 0x%03X, ctx, base); }" % (
                imp["name"], libs.get(imp["library"], 2), imp["ordinal"]))
    lines += [
        "",
        "alignas(16) static const unsigned char qaa_image[] = {",
        '#embed "image.bin"',
        "};",
        "",
        "static const qaa::ModuleImport qaa_imports[] = {",
    ]
    for imp in imports:
        lines.append("\t{ %s, 0x%03X, %s, 0x%08X, 0x%08X, %s }," % (
            c_string(imp["library"]), imp["ordinal"],
            "qaa::IMPORT_VARIABLE" if imp["kind"] == "variable" else "qaa::IMPORT_FUNCTION",
            imp["slot"] or 0, imp["thunk"] or 0, c_string(imp["name"])))
    if not imports:
        lines.append("\t{ nullptr, 0, 0, 0, 0, nullptr },")
    lines += ["};", "", "static const uint32_t qaa_exports[] = {"]
    for o in range(1, nexp + 1):
        lines.append("\t0x%08X," % exports.get(str(o), 0))
    if not nexp:
        lines.append("\t0,")
    lines += [
        "};",
        "",
        "static void qaa_bind(const qaa::ModuleHost *host) {",
        "\tqaa_module_func_pages = host->func_pages;",
        "\tqaa_module_indirect_miss = host->indirect_miss;",
        "\tqaa_module_trap = host->trap;",
        "\tqaa_kernel_call = host->kernel_call;",
        "}",
        "",
        "QAA_MODULE_EXPORT const qaa::ModuleDesc *qaa_module_describe(void) {",
        "\tstatic const qaa::ModuleDesc desc = {",
        "\t\tQAA_MODULE_ABI_VERSION,",
        "\t\t(uint32_t)sizeof(PPCContext),",
        "\t\tqaa::PpcConfigFlags(),",
        "\t\t%s," % c_string(name),
        "\t\t%s," % c_string(report["module"]),
        "\t\t%s," % c_string(recompiler_id),
        "\t\t0x%08X," % report["base"],
        "\t\t0x%08X," % report["image_size"],
        "\t\t0x%08X," % (report["entry"] or 0),
        "\t\t(uint32_t)sizeof(qaa_image),",
        "\t\tqaa_image,",
        "\t\treinterpret_cast<const qaa::FuncMapping *>(PPCFuncMappings),",
        "\t\tqaa_imports,",
        "\t\t%du," % len(imports),
        "\t\tqaa_exports,",
        "\t\t%du," % nexp,
        "\t\tqaa_bind,",
        "\t};",
        "\treturn &desc;",
        "}",
        "",
    ]
    path = os.path.join(out_dir, "qaa_module_glue.cpp")
    text = "\n".join(lines)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)
    return path
